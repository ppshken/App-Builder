const { test } = require('node:test');
const assert = require('node:assert/strict');
const Database = require('better-sqlite3');
const base = process.env.NOCODE_TEST_URL;
if (!base || !process.env.NOCODE_TEST_DB?.includes('integration-')) throw new Error('Use npm run test:api with its isolated database');
const column = (name, extra = {}) => ({ name, label: name, type: 'text', ...extra });
async function api(path, method = 'GET', body, expected = 200) {
  const r = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) });
  const j = await r.json(); assert.equal(r.status, expected, JSON.stringify(j));
  if (expected >= 400) assert.match(j.error, /[ก-๙]/);
  return j;
}
const create = (name, columns) => api('/api/tables', 'POST', { name, columns });
const patch = (table, body, expected = 200) => api(`/api/tables/${table}`, 'PATCH', body, expected);

test('runtime formulas, defaults, conditions, metadata editing and SQL safety end to end', async () => {
  await create('products', [column('name', { required: true }), column('qty', { type: 'number', default_expr: '2', valid_if: '[_THIS] >= 0', required: true }), column('price', { type: 'number', default_expr: '10' }), column('status', { type: 'enum', options: 'ทั่วไป,อื่น ๆ', default_expr: '"ทั่วไป"' }), column('note', { show_if: '[status] = "อื่น ๆ"', required_if: '[status] = "อื่น ๆ"' }), column('date', { type: 'date', default_expr: 'TODAY()' }), column('total', { type: 'number', is_virtual: true, virtual_expr: '[qty] * [price]' }), column('summary', { is_virtual: true, virtual_expr: 'CONCATENATE([name], "=", [total])' })]);
  const defaults = await api('/api/data/products?defaults=1');
  assert.equal(defaults.values.qty, 2); assert.equal(defaults.values.price, 10); assert.equal(defaults.values.status, 'ทั่วไป'); assert.match(defaults.values.date, /^\d{4}-\d{2}-\d{2}$/);
  assert.equal('total' in defaults.values, false);
  await api('/api/data/products', 'POST', {}, 400);
  await api('/api/data/products', 'POST', { name: 'ผิด', qty: -1 }, 400);
  await api('/api/data/products', 'POST', { name: 'ผิด', status: 'อื่น ๆ' }, 400);
  await api('/api/data/products', 'POST', { name: 'ผิด', status: 'ไม่มี' }, 400);
  await api('/api/data/products', 'POST', { name: 'ผิด', date: '2026-02-30' }, 400);
  const first = await api('/api/data/products', 'POST', { name: 'สินค้า', total: 999, summary: 'ปลอม' });
  const second = await api('/api/data/products', 'POST', { name: 'อีกชิ้น', qty: 5, price: 10, status: 'อื่น ๆ', note: 'ครบ' });
  let rows = await api('/api/data/products?sort=total&dir=asc');
  assert.deepEqual(rows.map(r => r.total), [20, 50]); assert.equal(rows[0].summary, 'สินค้า=20'); assert.equal(rows[0].__label, 'สินค้า');
  assert.equal((await api('/api/data/products?q=สินค้า%3D20')).length, 1);
  await api(`/api/data/products?id=${first.id}`, 'PUT', { qty: 4, total: 999 });
  rows = await api('/api/data/products'); assert.equal(rows.find(r => r.id === first.id).total, 40);
  await api(`/api/data/products?id=${first.id}`, 'PUT', { status: 'อื่น ๆ' }, 400);
  await api(`/api/data/products?id=${first.id}`, 'PUT', { name: null }, 400);
  await api('/api/data/products?id=9999', 'PUT', { name: 'ไม่มี' }, 404);
  await patch('products', { op: 'edit_column', name: 'total', virtual_expr: '[qty] * [price] * 2' });
  assert.equal((await api('/api/data/products')).find(r => r.id === first.id).total, 80);
  await patch('products', { op: 'edit_column', name: 'total', virtual_expr: '[missing]' }, 400);
  await patch('products', { op: 'edit_column', name: 'total', virtual_expr: '[summary]' }, 400);
  await patch('products', { op: 'edit_column', name: 'total', virtual_expr: 'IF(' }, 400);
  await patch('products', { op: 'edit_column', name: 'qty', type: 'text' }, 400);
  await patch('products', { op: 'edit_column', name: 'qty', is_virtual: true }, 400);
  await patch('products', { op: 'drop_column', name: 'qty' }, 400);
  await patch('products', { op: 'rename_column', name: 'qty', new_name: 'quantity' });
  const meta = (await api('/api/tables')).find(t => t.name === 'products');
  assert.equal(meta.columns.find(c => c.name === 'total').virtual_expr, '[quantity] * [price] * 2');
  await patch('products', { op: 'label', label: 'สินค้าไทย' });
  await patch('products', { op: 'add_column', column: column('unused') });
  await patch('products', { op: 'drop_column', name: 'unused' });
  assert.equal((await api('/api/data/products')).length, 2);
  await patch('products', { op: 'add_column', column: column('virtual_name', { is_virtual: true, virtual_expr: 'UPPER([name])' }) });
  await patch('products', { op: 'rename_column', name: 'virtual_name', new_name: 'capital_name' });
  await patch('products', { op: 'drop_column', name: 'capital_name' });
  const db = new Database(process.env.NOCODE_TEST_DB, { readonly: true });
  const physical = db.pragma("table_info('t_products')").map(c => c.name);
  assert.equal(physical.includes('total'), false); assert.equal(physical.includes('summary'), false); assert.equal(physical.includes('quantity'), true);
  assert.equal(db.pragma("table_info('t_products')").find(c => c.name === 'name').notnull, 0); db.close();
  await create('orders', [column('customer', { type: 'ref', ref_table: 'products' })]);
  const order = await api('/api/data/orders', 'POST', { customer: first.id });
  assert.equal((await api('/api/data/orders'))[0].customer__label, 'สินค้า');
  await api('/api/tables/products', 'DELETE', undefined, 400);
  await api(`/api/data/products?id=${first.id}`, 'DELETE', undefined, 400);
  await api('/api/data/orders', 'POST', { customer: 9999 }, 400);
  await api(`/api/data/orders?id=${order.id}`, 'DELETE');
  await api('/api/tables/orders', 'DELETE');
  await api(`/api/data/products?id=${second.id}`, 'DELETE');
  await create('virtual_only', [column('answer', { type: 'number', is_virtual: true, virtual_expr: '42' })]);
  await api('/api/data/virtual_only', 'POST', {}); assert.equal((await api('/api/data/virtual_only'))[0].answer, 42);
  await create('ref_virtual', [column('display', { is_virtual: true, virtual_expr: '"ชื่อตามสูตร"' })]);
  const virtualRow = await api('/api/data/ref_virtual', 'POST', {});
  await create('references', [column('target', { type: 'ref', ref_table: 'ref_virtual' })]);
  await api('/api/data/references', 'POST', { target: virtualRow.id });
  assert.equal((await api('/api/data/references'))[0].target__label, 'ชื่อตามสูตร');
  for (const name of ['id', 'UPPER', 'a";DROP TABLE _tables;--']) await api('/api/tables', 'POST', { name, columns: [column('name')] }, 400);
  await api('/api/tables', 'POST', { name: 'evil', columns: [column('name', { type: 'constructor' })] }, 400);
  await patch('products', { op: 'rename_column', name: 'price', new_name: 'id' }, 400);
  const malformed = await fetch(base + '/api/data/products', { method: 'POST', body: '{' }); assert.equal(malformed.status, 400);
  assert.ok((await api('/api/tables')).length >= 4);
});
