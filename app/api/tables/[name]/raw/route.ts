import {tableOverlay} from '@/lib/shared-table-columns';
import {columnsOf} from '@/lib/db';
import {rowVersion} from '@/lib/row-version';
import {tableAccess} from '@/lib/access';
import {currentAccess,canRead} from '@/lib/permissions';
import {currentApplication} from '@/lib/application-context';
import {NextResponse} from 'next/server';
import {withAuth} from '@/lib/auth-api';
import {db,tableExists} from '@/lib/db';
import {bad,errorMessage,errorStatus} from '@/lib/api';
import {rawQuery,parseRawQuery} from '@/lib/raw-query';
import {assertRawManager} from '@/lib/raw-data-jobs';
export const dynamic='force-dynamic';
export const GET=withAuth(async(req:Request,{params}:{params:{name:string}})=>{try{
const t=params.name;if(!tableExists(t))return bad('ไม่พบตาราง',404);
assertRawManager(t);
const u=new URL(req.url),requested=Number(u.searchParams.get('page')||1),size=Number(u.searchParams.get('page_size')||25);
if(!Number.isSafeInteger(requested)||requested<1||![10,25,50,100].includes(size))return bad('หน้าหรือจำนวนรายการต่อหน้าไม่ถูกต้อง');
const columns=(db.prepare('PRAGMA table_info("t_'+t+'")').all() as {name:string;type:string}[]).map(c=>({name:c.name,type:c.type}));
const plan=rawQuery(parseRawQuery(u.searchParams.get('query')),columns);
const total=(db.prepare('SELECT COUNT(*) AS total FROM "t_'+t+'" WHERE '+plan.where).get(...plan.args) as {total:number}).total,pages=Math.max(1,Math.ceil(total/size)),page=Math.min(requested,pages);
const rows=db.prepare('SELECT * FROM "t_'+t+'" WHERE '+plan.where+' ORDER BY '+plan.order+' LIMIT ? OFFSET ?').all(...plan.args,size,(page-1)*size);
const fields=columnsOf(t).filter(c=>!c.is_virtual),rights=tableAccess(currentAccess(),t);
return NextResponse.json({columns,rows,total,page,pages,appId:currentApplication()?.id,rights,fields:fields.map(c=>({name:c.name,label:c.label,type:c.type,...(c.type==='ref'&&c.ref_table?{ref_table:c.ref_table,ref_label:canRead(c.ref_table)&&tableExists(c.ref_table)?(tableOverlay(db,c.ref_table)?.label||(db.prepare('SELECT label FROM _tables WHERE name=?').get(c.ref_table) as {label:string}|undefined)?.label):undefined}:{}),editable:c.is_editable!==false&&c.is_editable!==0&&!c.auto_number&&!c.virtual_expr})),versions:Object.fromEntries((rows as Record<string,any>[]).map(row=>[row.id,rowVersion(t,fields,row)]))});
}catch(e){return bad(errorMessage(e),errorStatus(e));}});
